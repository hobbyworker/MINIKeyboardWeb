// Where the cross-platform app draws its layouts' controls: its own geometry, in its window's space.

import { ControlId, type KnobPart } from "$domain";
import { LayoutRect } from "./rect";

const r = LayoutRect.of;
const key = (number: number): ControlId => ControlId.key(number);
const knob = (number: number, part: KnobPart): ControlId => ControlId.knob(number, part);

type Placed = readonly (readonly [ControlId, LayoutRect])[];

/** A layout's body and where each of its controls is drawn; `null` for a layout the app has no geometry for. */
export function appGeometry(id: string): { readonly frame: LayoutRect; readonly rects: Placed } | null {
    const found = APP.find(([name]) => name === id);
    return found === undefined ? null : { frame: found[1], rects: found[2] };
}

